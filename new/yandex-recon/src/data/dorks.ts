/**
 * All dork templates combined.
 */
export const ALL_DORKS: Dork[] = [...DORK_TEMPLATES, ...EXTRA_DORKS];

/**
 * Generate all dork instances for a given domain.
 */
export function generateDorks(domain: string) {
  return ALL_DORKS.map((dork) => ({
    id: dork.id,
    category: dork.category,
    severity: dork.severity,
    title: dork.title,
    description: dork.description,
    query: dork.query(domain),
    isFavorite: false,
  }));
}

